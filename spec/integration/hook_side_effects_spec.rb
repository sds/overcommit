# frozen_string_literal: true

require 'spec_helper'

[false, true].each do |initial_commit|
  context_name = initial_commit ? 'on an initial commit' : 'with existing history'
  describe "pre-commit side effects #{context_name}" do
    let(:hook_result) { ':pass' }
    let(:hook_body) do
      <<~RUBY_CODE
        raise 'Saw unstaged changes' if File.read('source.txt').include?('unstaged')
        File.write('generated.txt', "Generated by hook\\n")
        execute(%w[git add generated.txt])
        execute(%w[git rm -f removed.txt])
        File.write('source.txt', File.read('source.txt').sub('staged', 'formatted'))
        execute(%w[git add source.txt])
        #{hook_result}
      RUBY_CODE
    end

    around do |example|
      repo do
        echo({
          'CommitMsg' => { 'ALL' => { 'enabled' => false } },
          'PreCommit' => {
            'ALL' => { 'enabled' => false },
            'SideEffects' => { 'enabled' => true, 'requires_files' => false,
                               'parallelize' => false },
          },
        }.to_yaml, '.overcommit.yml')
        FileUtils.mkdir_p('.git-hooks/pre_commit')
        echo(<<~RUBY_CODE, '.git-hooks/pre_commit/side_effects.rb')
          module Overcommit::Hook::PreCommit
            class SideEffects < Base
              def run
                #{hook_body}
              end
            end
          end
        RUBY_CODE
        echo('original', 'source.txt')
        echo('remove me', 'removed.txt')
        shell(%w[git add .]).status.should == 0
        shell(%w[git commit -m Initial]).status.should == 0 unless initial_commit
        echo((['staged'] + (1..10).map(&:to_s)).join("\n"), 'source.txt')
        shell(%w[git add source.txt]).status.should == 0
        echo('unstaged', 'source.txt', append: true)
        install_overcommit_hooks
        example.run
      end
    end

    it 'commits hook additions, deletions, and edits while leaving user changes unstaged' do
      result = shell(%w[git commit -m Test])
      expect(result.status).to eq(0), result.stdout + result.stderr
      shell(%w[git show HEAD:generated.txt]).stdout.should == "Generated by hook\n"
      shell(%w[git show HEAD:source.txt]).stdout.should start_with("formatted\n")
      shell(%w[git show HEAD:source.txt]).stdout.should_not include 'unstaged'
      shell(%w[git ls-tree --name-only HEAD]).stdout.should_not include 'removed.txt'
      File.read('source.txt').should end_with("unstaged\n")
      shell(%w[git diff --cached]).stdout.should == ''
      shell(%w[git stash list]).stdout.should == ''
    end

    context 'when the hook fails' do
      let(:hook_result) { '[:fail, "Intentional failure"]' }

      it 'aborts the commit while retaining hook edits and restoring user edits' do
        head = shell(%w[git rev-parse --verify HEAD]).stdout
        result = shell(%w[git commit -m Test])
        result.status.should_not == 0
        (result.stdout + result.stderr).should include 'Intentional failure'
        shell(%w[git rev-parse --verify HEAD]).stdout.should == head
        shell(%w[git show :generated.txt]).stdout.should == "Generated by hook\n"
        shell(%w[git show :source.txt]).stdout.should start_with("formatted\n")
        File.read('source.txt').should end_with("unstaged\n")
        File.exist?('removed.txt').should == false
        shell(%w[git stash list]).stdout.should == ''
      end
    end

    context 'when the hook is interrupted' do
      let(:hook_result) { 'raise Interrupt' }

      it 'aborts the commit and restores user edits without discarding hook edits' do
        result = shell(%w[git commit -m Test])
        result.status.should_not == 0
        File.read('source.txt').should start_with("formatted\n")
        File.read('source.txt').should end_with("unstaged\n")
        shell(%w[git show :generated.txt]).stdout.should == "Generated by hook\n"
      end
    end

    context 'when the hook raises' do
      let(:hook_result) { "raise 'Intentional error'" }

      it 'restores user edits even after a hook exception' do
        result = shell(%w[git commit -m Test])
        result.status.should_not == 0
        (result.stdout + result.stderr).should include 'Intentional error'
        File.read('source.txt').should start_with("formatted\n")
        File.read('source.txt').should end_with("unstaged\n")
        shell(%w[git show :generated.txt]).stdout.should == "Generated by hook\n"
      end
    end
  end
end
